#!/usr/bin/env bash
# =============================================================================
#  CloudFlow — one-shot free-tier deploy
#  Neon (Postgres)  +  Railway (API + single-node Kafka)  +  Vercel (UI + worker)
#
#  Usage
#    bash scripts/deploy-cloud.sh             # full deploy, then live checks
#    bash scripts/deploy-cloud.sh --verify    # re-run only the live checks
#    bash scripts/deploy-cloud.sh --status     # print saved URLs / form values
#
#  Required token files (already gitignored — never commit them):
#    .railway-token   https://railway.com/account/tokens        (account token)
#    .neon-token      https://console.neon.tech/app/settings/api-keys
#    .vercel-token    https://vercel.com/account/settings/tokens
#
#  Optional overrides (env vars):
#    PROJECT_NAME (cloudflow)  API_SERVICE (api)  KAFKA_SERVICE (kafka)
#    VERCEL_PROJECT (cloudflow-web)  KAFKA_IMAGE (apache/kafka:4.1.2)
#    SEED_BULK (50000)  NEON_REGION (provider default)
#    RAILWAY_PROJECT_ID (unset) — link an existing Railway project instead of
#      creating one; required on the free plan, which allows a single project.
#
#  Why this order: Kafka is deployed before the API so the embedded consumer
#  finds a live broker on its first connection attempt (kafkajs only retries
#  five times), and Vercel is deployed before CORS_ORIGIN is patched on Railway.
# =============================================================================
set -euo pipefail

# Git Bash on Windows rewrites /tmp/... inside arguments to C:/Users/.../Temp/...
# which corrupts container paths such as KAFKA_LOG_DIRS. Disable that conversion.
export MSYS_NO_PATHCONV=1
export MSYS2_ARG_CONV_EXCL='*'

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

PROJECT_NAME="${PROJECT_NAME:-cloudflow}"
API_SERVICE="${API_SERVICE:-api}"
KAFKA_SERVICE="${KAFKA_SERVICE:-kafka}"
VERCEL_PROJECT="${VERCEL_PROJECT:-cloudflow-web}"
KAFKA_IMAGE="${KAFKA_IMAGE:-apache/kafka:4.1.2}"
SEED_BULK="${SEED_BULK:-50000}"
NEON_REGION="${NEON_REGION:-}"
RAILWAY_PROJECT_ID="${RAILWAY_PROJECT_ID:-}"

STATE_FILE="$ROOT/.deploy.env"
TOOLS="$ROOT/.deploy-tools"

step() { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
info() { printf '    %s\n' "$*"; }
warn() { printf '\033[1;33m    ! %s\033[0m\n' "$*"; }
die()  { printf '\033[1;31m    x %s\033[0m\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------------------
# state file (.deploy.env) — keeps re-runs idempotent
# ---------------------------------------------------------------------------
state_get() {
  local key="$1"
  if [ ! -f "$STATE_FILE" ]; then printf ''; return 0; fi
  sed -n "s/^${key}=//p" "$STATE_FILE" | tail -n1
}

state_set() {
  local kv="$1" key="${1%%=*}" tmp="$STATE_FILE.tmp"
  if [ -f "$STATE_FILE" ]; then
    grep -v "^${key}=" "$STATE_FILE" > "$tmp" || true
  else
    printf '# generated by scripts/deploy-cloud.sh — do not commit\n' > "$tmp"
  fi
  printf '%s\n' "$kv" >> "$tmp"
  mv "$tmp" "$STATE_FILE"
}

# ---------------------------------------------------------------------------
# preflight
# ---------------------------------------------------------------------------
preflight() {
  step "Preflight"
  command -v node >/dev/null 2>&1 || die "node is required"
  command -v npm  >/dev/null 2>&1 || die "npm is required"
  command -v curl >/dev/null 2>&1 || die "curl is required"
  info "node $(node -v)  npm $(npm -v)"

  RAILWAY_TOKEN_VALUE="$(read_token '.railway-token' 'Railway account')"
  NEON_TOKEN_VALUE="$(read_token '.neon-token' 'Neon API')"
  VERCEL_TOKEN_VALUE="$(read_token '.vercel-token' 'Vercel')"
  info "tokens loaded from .railway-token .neon-token .vercel-token"
}

read_token() {
  local file="$1" label="$2"
  [ -f "$file" ] || die "missing $file — save your $label token there (see script header)"
  local value
  value="$(tr -d ' \t\r\n' < "$file")"
  [ -n "$value" ] || die "$file is empty — paste your $label token into it and save"
  case "$value" in
    PASTE_*|*PASTE_YOUR*|paste*|your_*)
      die "$file still holds the placeholder — replace it with the real $label token (all lines deleted, one line, no quotes) and save" ;;
  esac
  printf '%s' "$value"
}

# ---------------------------------------------------------------------------
# CLIs, installed locally into .deploy-tools (no global npm changes)
# ---------------------------------------------------------------------------
ensure_tools() {
  step "Tooling"
  mkdir -p "$TOOLS"

  # Prefer an already-installed CLI; otherwise install locally (no global npm changes).
  if command -v railway >/dev/null 2>&1; then
    RAILWAY="$(command -v railway)"
  else
    RAILWAY="$TOOLS/node_modules/.bin/railway"
    if [ ! -f "$RAILWAY" ]; then
      info "installing @railway/cli into .deploy-tools"
      npm install --prefix "$TOOLS" --no-audit --no-fund --loglevel=error \
        '@railway/cli@^5.75.0' >/dev/null 2>&1 || true
    fi
  fi

  if command -v vercel >/dev/null 2>&1; then
    VERCEL="$(command -v vercel)"
  else
    VERCEL="$TOOLS/node_modules/.bin/vercel"
    if [ ! -f "$VERCEL" ]; then
      info "installing vercel into .deploy-tools"
      npm install --prefix "$TOOLS" --no-audit --no-fund --loglevel=error \
        'vercel@^66.6.0' >/dev/null 2>&1 || true
    fi
  fi

  # npm's sh shims are not executable by default on Windows/Git Bash
  chmod +x "$RAILWAY" "$VERCEL" 2>/dev/null || true
  [ -x "$RAILWAY" ] || die "railway CLI missing or not runnable ($RAILWAY) — run: npm i -g @railway/cli"
  [ -x "$VERCEL" ]  || die "vercel CLI missing or not runnable ($VERCEL) — run: npm i -g vercel"
  # Account token (not a project token) — required to create the project.
  export RAILWAY_API_TOKEN="$RAILWAY_TOKEN_VALUE"
  unset RAILWAY_TOKEN 2>/dev/null || true
  export VERCEL_TOKEN="$VERCEL_TOKEN_VALUE"
  info "$("$RAILWAY" --version 2>&1 | grep -v '^[[:space:]]*$' | head -n1)  |  $("$VERCEL" --version 2>&1 | grep -v '^[[:space:]]*$' | tail -n1)"
}

# ---------------------------------------------------------------------------
# 1. Neon Postgres
# ---------------------------------------------------------------------------
create_neon() {
  step "Neon Postgres"
  local existing
  existing="$(state_get DATABASE_URL)"
  if [ -n "$existing" ]; then
    DATABASE_URL="$existing"
    info "reusing saved DATABASE_URL"
    return 0
  fi

  local payload resp
  if [ -n "$NEON_REGION" ]; then
    payload="$(printf '{"project":{"name":"%s","region_id":"%s"}}' "$PROJECT_NAME" "$NEON_REGION")"
  else
    payload="$(printf '{"project":{"name":"%s"}}' "$PROJECT_NAME")"
  fi

  info "creating Neon project \"$PROJECT_NAME\""
  resp="$(curl -fsS -X POST 'https://console.neon.tech/api/v2/projects' \
    -H "Authorization: Bearer $NEON_TOKEN_VALUE" \
    -H 'Content-Type: application/json' \
    -H 'Accept: application/json' \
    -d "$payload")" || die "Neon project creation failed (check .neon-token)"

  DATABASE_URL="$(printf '%s' "$resp" | node -e '
    let s = "";
    process.stdin.on("data", (d) => (s += d)).on("end", () => {
      let j;
      try { j = JSON.parse(s); } catch { console.error("Neon returned non-JSON"); process.exit(1); }
      const uri = (j.connection_uris || [])[0]?.connection_uri;
      if (!uri) { console.error(JSON.stringify(j).slice(0, 400)); process.exit(1); }
      process.stdout.write(uri);
    });')" || die "could not read a connection URI from the Neon response"

  case "$DATABASE_URL" in
    *sslmode=*) ;;
    *\?*) DATABASE_URL="${DATABASE_URL}&sslmode=require" ;;
    *)    DATABASE_URL="${DATABASE_URL}?sslmode=require" ;;
  esac

  state_set "DATABASE_URL=$DATABASE_URL"
  info "connection string saved to .deploy.env"
}

# ---------------------------------------------------------------------------
# 2. Schema + seed
# ---------------------------------------------------------------------------
migrate_and_seed() {
  step "Schema + seed on Neon"
  DATABASE_URL="$DATABASE_URL" PG_SSL=true npm --prefix backend run migrate

  local seeded
  seeded="$(state_get SEED_BULK)"
  if [ "$seeded" = "$SEED_BULK" ]; then
    info "seed already applied (SEED_BULK=$SEED_BULK) — skipping"
    return 0
  fi

  info "seeding tenants + $SEED_BULK bulk orders (EXPLAIN ANALYZE dataset)"
  DATABASE_URL="$DATABASE_URL" PG_SSL=true npm --prefix backend run seed -- "$SEED_BULK"
  state_set "SEED_BULK=$SEED_BULK"
}

# ---------------------------------------------------------------------------
# 3. Railway: project, Kafka (image), API (source upload)
# ---------------------------------------------------------------------------
railway_service_exists() {
  local name="$1" list
  list="$("$RAILWAY" service list --json 2>/dev/null || printf '[]')"
  printf '%s' "$list" | node -e '
    let s = "";
    process.stdin.on("data", (d) => (s += d)).on("end", () => {
      const wanted = String(process.argv[process.argv.length - 1] || "").toLowerCase();
      let arr = [];
      try { arr = JSON.parse(s); } catch { process.exit(1); }
      arr = Array.isArray(arr) ? arr : (arr.services || arr.edges?.map((e) => e.node) || []);
      const hit = arr.some((x) => {
        const n = x?.name || x?.service?.name || x?.node?.name || "";
        return String(n).toLowerCase() === wanted;
      });
      process.exit(hit ? 0 : 1);
    });' "$name"
}

railway_create_project() {
  local saved
  saved="$(state_get RAILWAY_PROJECT_ID)"
  [ -n "$saved" ] || saved="$RAILWAY_PROJECT_ID"
  if [ -n "$saved" ]; then
    info "linking existing project $saved (free plan allows one project)"
    "$RAILWAY" link -p "$saved" -e production --json >/dev/null 2>&1 \
      || die "could not link Railway project $saved — check the id and the token's workspace access"
    state_set "RAILWAY_PROJECT_ID=$saved"
    return 0
  fi

  info "creating Railway project \"$PROJECT_NAME\""
  local out
  out="$("$RAILWAY" init --name "$PROJECT_NAME" --json 2>&1)" || die "railway init failed:
$out
    hint: the free plan only allows one project. Re-run with
    RAILWAY_PROJECT_ID=<existing-project-id> bash scripts/deploy-cloud.sh"
  local pid
  pid="$(printf '%s' "$out" | node -e '
    let s = "";
    process.stdin.on("data", (d) => (s += d)).on("end", () => {
      let j;
      try { j = JSON.parse(s); } catch { process.exit(1); }
      const p = j.project || j;
      const id = p.id || p.projectId || j.projectId || "";
      if (!id) process.exit(1);
      process.stdout.write(id);
    });')" || die "could not parse project id from: $out"

  state_set "RAILWAY_PROJECT_ID=$pid"
  info "project id $pid"
}

