create_railway_kafka() {
  step "Railway service: Kafka ($KAFKA_IMAGE)"
  if railway_service_exists "$KAFKA_SERVICE"; then
    info "service \"$KAFKA_SERVICE\" already exists — skipping create"
    return 0
  fi

  local args=()
  while IFS= read -r kv; do args+=(-v "$kv"); done < <(railway_kafka_vars)

  "$RAILWAY" add --image "$KAFKA_IMAGE" --service "$KAFKA_SERVICE" "${args[@]}" \
    || die "could not create the Kafka service"

  info "waiting for the broker to start before deploying the API"
  local i status
  for i in $(seq 1 40); do
    sleep 6
    status="$("$RAILWAY" service status --service "$KAFKA_SERVICE" --json 2>/dev/null | tr -d '\r' || true)"
    case "$status" in
      *SUCCESS*|*RUNNING*) info "broker reported $([ "${#status}" -lt 160 ] && printf '%s' "$status" || printf 'running')"; break ;;
    esac
    if [ "$i" -eq 40 ]; then warn "broker did not report RUNNING in 4 min — continuing anyway"; fi
  done
  # KRaft needs a few more seconds after the container is up to accept clients.
  sleep 20
}

create_railway_api() {
  step "Railway service: API ($API_SERVICE)"
  if ! railway_service_exists "$API_SERVICE"; then
    "$RAILWAY" add --service "$API_SERVICE" || die "could not create the API service"
  else
    info "service \"$API_SERVICE\" already exists"
  fi

  local jwt brokers
  jwt="$(node -e 'process.stdout.write(require("node:crypto").randomBytes(32).toString("hex"))')"
  brokers="${KAFKA_SERVICE}.railway.internal:9092"

  local vars=(
    "NODE_ENV=production"
    "SERVE_FRONTEND=false"
    "RUN_EMBEDDED_CONSUMER=true"
    "DATABASE_URL=$DATABASE_URL"
    "PG_SSL=true"
    "PG_POOL_MAX=20"
    "PG_POOL_MIN=2"
    "PG_IDLE_TIMEOUT_MS=30000"
    "PG_CONNECTION_TIMEOUT_MS=5000"
    "JWT_SECRET=$jwt"
    "JWT_EXPIRES_IN=8h"
    "KAFKA_CLIENT_ID=multitenant-saas-platform"
    "KAFKA_BROKERS=$brokers"
    "KAFKA_TOPIC_ORDERS=tenant.orders"
    "KAFKA_CONSUMER_GROUP=order-processor-group"
    "KAFKA_SSL=false"
    "CORS_ORIGIN=https://placeholder.vercel.app"
  )

  info "pushing ${#vars[@]} environment variables (deploys deferred)"
  local kv
  for kv in "${vars[@]}"; do
    "$RAILWAY" variable set "$kv" --service "$API_SERVICE" --skip-deploys --json >/dev/null \
      || die "failed to set variable ${kv%%=*}"
  done
}

deploy_railway_api() {
  step "Building + deploying the API"
  info "uploading backend/ (npm install, node src/server.js)"
  "$RAILWAY" up ./backend --path-as-root --service "$API_SERVICE" --ci \
    || die "the API build failed — run: $RAILWAY logs --build --service $API_SERVICE"
}

create_railway_domain() {
  step "Public domain"
  local saved
  saved="$(state_get API_URL)"
  if [ -n "$saved" ]; then API_URL="$saved"; info "reusing $API_URL"; return 0; fi

  local out
  out="$("$RAILWAY" domain --service "$API_SERVICE" --json 2>&1)" || die "domain creation failed:
$out"
  local host
  host="$(printf '%s' "$out" | node -e '
    let s = "";
    process.stdin.on("data", (d) => (s += d)).on("end", () => {
      const m = s.match(/[a-z0-9-]+\.up\.railway\.app/);
      if (!m) { console.error(s.slice(0, 300)); process.exit(1); }
      process.stdout.write(m[0]);
    });')" || die "could not parse a domain from: $out"

  API_URL="https://$host"
  state_set "API_URL=$API_URL"
  info "$API_URL"
}

# ---------------------------------------------------------------------------
# 4. Vercel: project, build-time API base, production deploy
# ---------------------------------------------------------------------------
deploy_vercel() {
  step "Vercel frontend + serverless worker"
  local saved
  saved="$(state_get WEB_URL)"
  if [ -n "$saved" ] && [ "${FORCE_VERCEL:-0}" != "1" ]; then
    WEB_URL="$saved"; info "reusing $saved (FORCE_VERCEL=1 to redeploy)"; return 0
  fi

  # vercel.json at the repo root owns buildCommand/outputDirectory/functions,
  # so the project must stay at root directory "." with no framework preset.
  "$VERCEL" project create "$VERCEL_PROJECT" --token "$VERCEL_TOKEN_VALUE" >/dev/null 2>&1 \
    || info "project already exists (or was just created)"
  "$VERCEL" link --yes --project "$VERCEL_PROJECT" --token "$VERCEL_TOKEN_VALUE" >/dev/null \
    || die "vercel link failed — create the project once in the dashboard, then re-run"

  info "setting VITE_API_BASE_URL=$API_URL (build-time, inlined by Vite)"
  "$VERCEL" env add VITE_API_BASE_URL production --value "$API_URL" --force --yes \
    --token "$VERCEL_TOKEN_VALUE" >/dev/null
  "$VERCEL" env add VITE_API_BASE_URL preview --value "$API_URL" --force --yes \
    --token "$VERCEL_TOKEN_VALUE" >/dev/null

  info "deploying (npm run build inside frontend/)"
  local out
  out="$("$VERCEL" deploy --prod --yes --token "$VERCEL_TOKEN_VALUE" 2>&1)" || {
    printf '%s\n' "$out" | tail -n 25
    die "vercel deploy failed"
  }
  local url
  url="$(printf '%s' "$out" | node -e '
    let s = "";
    process.stdin.on("data", (d) => (s += d)).on("end", () => {
      const all = s.match(/https:\/\/[a-z0-9-]+\.vercel\.app/g);
      if (!all) { console.error(s.slice(-500)); process.exit(1); }
      process.stdout.write(all[all.length - 1]);
    });')" || die "could not parse the deployment URL"

  WEB_URL="$url"
  state_set "WEB_URL=$WEB_URL"
  info "$WEB_URL"
}

# ---------------------------------------------------------------------------
# 5. Patch the API with the real frontend origin, redeploy
# ---------------------------------------------------------------------------
patch_railway_urls() {
  step "Wiring CORS + serverless worker URL"
  "$RAILWAY" variable set "CORS_ORIGIN=$WEB_URL" --service "$API_SERVICE" --skip-deploys --json >/dev/null
  "$RAILWAY" variable set "SERVERLESS_INVOICE_URL=$WEB_URL/api/invoice-worker" \
    --service "$API_SERVICE" --skip-deploys --json >/dev/null
  "$RAILWAY" redeploy --service "$API_SERVICE" --yes >/dev/null 2>&1 \
    || warn "redeploy command failed; the next \`railway up\` will pick the variables up"
}

# ---------------------------------------------------------------------------
# 6. Live verification — the same proof the lab asks for
# ---------------------------------------------------------------------------
verify_live() {
  step "Live verification"
  [ -n "${API_URL:-}" ] || die "no API_URL in .deploy.env — run a full deploy first"

  node - "$API_URL" "${WEB_URL:-}" <<'NODE_EOF'
const [api, web] = process.argv.slice(2);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let failures = 0;

const pass = (m) => console.log(`\x1b[32m    ✓ ${m}\x1b[0m`);
const fail = (m) => { failures += 1; console.log(`\x1b[31m    x ${m}\x1b[0m`); };
const note = (m) => console.log(`      ${m}`);

const req = async (url, { method = 'GET', token, body, tenant } = {}) => {
  const headers = { 'Content-Type': 'application/json' };
  if (token) headers.Authorization = `Bearer ${token}`;
  if (tenant) headers['x-tenant-id'] = tenant;
  const res = await fetch(url, { method, headers, body: body ? JSON.stringify(body) : undefined });
  const text = await res.text();
  let json; try { json = JSON.parse(text); } catch { json = null; }
  return { status: res.status, json, text, headers: res.headers };
};

(async () => {
  // 1. health (Neon may need to wake from scale-to-zero)
  let health = null;
  for (let i = 0; i < 60; i += 1) {
    try {
      const r = await req(`${api}/api/v1/health`);
      if (r.status === 200 && r.json?.database?.status === 'up') { health = r.json; break; }
      if (i === 0) note(`health still ${r.status} (database ${r.json?.database?.status || '?'}) — retrying`);
    } catch (err) { if (i === 0) note(`health unreachable (${err.message}) — retrying`); }
    await sleep(3000);
  }
  if (!health) { fail('GET /api/v1/health never returned 200 with database.status=up'); return done(); }
  pass(`health 200 — database=${health.database.status}, kafka.topic=${health.kafka.topic}, brokers=${health.kafka.brokers}`);
  pass(`serverless mode=${health.serverless.mode} -> ${health.serverless.url}`);
  if (!health.kafka.producerConnected) fail('Kafka producer is not connected (broker unreachable from the API)');

  // 2. login both tenants
  const loginA = await req(`${api}/api/v1/auth/login`, { method: 'POST', body: { email: 'admin@acme-corp.io', password: 'TenantA!Password123', tenantSlug: 'acme-corp' } });
  const loginB = await req(`${api}/api/v1/auth/login`, { method: 'POST', body: { email: 'admin@globex-inc.io', password: 'TenantB!Password123', tenantSlug: 'globex-inc' } });
  if (loginA.status !== 200 || !loginA.json?.token) { fail(`tenant A login failed (${loginA.status}) — did the seed run?`); return done(); }
  if (loginB.status !== 200 || !loginB.json?.token) { fail(`tenant B login failed (${loginB.status})`); return done(); }
  const A = loginA.json.token, B = loginB.json.token;
  pass('tenant A + tenant B logins 200');

  // 3. order -> 202 -> Kafka consumer confirms
  const order = await req(`${api}/api/v1/orders`, {
    method: 'POST', token: A, tenant: loginA.json.tenant.id,
    body: { items: [{ productId: 'a1000000-0000-4000-8000-000000000001', quantity: 2 }] },
  });
  if (order.status !== 202 || !order.json?.orderId) {
    fail(`POST /api/v1/orders returned ${order.status}: ${order.text.slice(0, 200)}`);
    return done();
  }
  const orderId = order.json.orderId;
  pass(`order ${orderId} accepted 202 (status ${order.json.status}, partition ${order.json.kafka?.partition}, offset ${order.json.kafka?.offset})`);

  let confirmed = false, current = null;
  for (let i = 0; i < 45; i += 1) {
    await sleep(2000);
    const r = await req(`${api}/api/v1/orders/${orderId}`, { token: A, tenant: loginA.json.tenant.id });
    current = r.json?.order || null;
    if (current?.status === 'CONFIRMED') { confirmed = true; break; }
  }
  if (confirmed) pass(`consumer committed: order status = CONFIRMED after ${current?.updated_at || 'n/a'}`);
  else fail(`order never reached CONFIRMED (last status: ${current?.status || 'unknown'}) — check the embedded consumer logs`);

  // 4. invoice PDF
  const pdf = await fetch(`${api}/api/v1/diagnostics/invoices/${orderId}/pdf`, { headers: { Authorization: `Bearer ${A}` } });
  const buf = Buffer.from(await pdf.arrayBuffer());
  if (pdf.status === 200 && buf.length > 500 && buf.subarray(0, 4).toString() === '%PDF') {
    pass(`invoice PDF 200, ${buf.length} bytes, %PDF header intact`);
  } else {
    fail(`invoice PDF failed: status ${pdf.status}, ${buf.length} bytes`);
  }

  // 5. tenant isolation
  const leak = await req(`${api}/api/v1/orders/${orderId}`, { token: B, tenant: loginB.json.tenant.id });
  if (leak.status === 404) pass('cross-tenant read as tenant B -> 404 (no data leak)');
  else fail(`tenant B could read tenant A order: ${leak.status}`);

  const spoof = await req(`${api}/api/v1/orders/${orderId}`, { token: A, tenant: loginB.json.tenant.id });
  if (spoof.status === 403 && /cross-tenant/i.test(JSON.stringify(spoof.json || {}))) {
    pass(`JWT/header mismatch -> 403 "${spoof.json.error}"`);
  } else {
    fail(`JWT/header mismatch expected 403, got ${spoof.status}`);
  }

  // 6. cold-start benchmark through the Vercel worker
  const cold = await req(`${api}/api/v1/diagnostics/cold-start-test`, { method: 'POST', token: A, tenant: loginA.json.tenant.id, body: { warmCount: 2 } });
  if (cold.status === 200) {
    const s = cold.json.summary;
    pass(`cold-start: ${s.coldLatencyMs} ms vs warm avg ${s.avgWarmLatencyMs} ms (ratio ${s.coldVsWarmRatio}x), mode ${cold.json.coldStart.invocationMode}`);
  } else {
    fail(`cold-start test returned ${cold.status}: ${cold.text.slice(0, 160)}`);
  }

  // 7. the serverless function itself
  if (web) {
    try {
      const w = await req(`${web}/api/invoice-worker`);
      if (w.status === 200 && w.json?.instanceId) {
        pass(`Vercel worker reachable — instanceId ${String(w.json.instanceId).slice(0, 12)}…, isWarm=${w.json.isWarm}`);
      } else {
        fail(`GET ${web}/api/invoice-worker returned ${w.status} (expected worker telemetry JSON)`);
      }
    } catch (err) { fail(`Vercel worker unreachable: ${err.message}`); }
  }

  done();
})();

